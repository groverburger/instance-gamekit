pub const CHAR_W: i32 = 6;
pub const CHAR_H: i32 = 8;

fn glyph(c: char) -> &'static [&'static str; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?')).map(|(_, rows)| rows).unwrap()
}

/// Width in pixels of `text` at `scale`.
pub fn text_width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * CHAR_W * scale
}

/// Draws `text` with its top-left corner at (x, y).
pub fn draw_text(cv: &mut Canvas, x: i32, y: i32, text: &str, c: Rgba, scale: i32) {
    for (i, ch) in text.chars().enumerate() {
        let rows = glyph(ch);
        for (gy, row) in rows.iter().enumerate() {
            for (gx, b) in row.bytes().enumerate() {
                if b == b'#' {
                    let px = x + (i as i32 * CHAR_W + gx as i32) * scale;
                    let py = y + gy as i32 * scale;
                    cv.rect(px, py, scale, scale, c);
                }
            }
        }
    }
}
